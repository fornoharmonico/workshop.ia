export const OFFICIAL_PROMPTS: OfficialPrompt[] = PILOT_CHAIN_ACTIVITIES.map((act, index) => {
  const contextHeader = CONTEXT_BLOCKS[act.id] || '';
  const fullTemplate = contextHeader 
    ? `${contextHeader}\n\n---\n\n${act.aiPrompt.templatePrompt}`
    : act.aiPrompt.templatePrompt;

  return {
    id: `prompt-${(index + 1).toString().padStart(2, '0')}`,
    activityId: act.id,
    number: index + 1,
    title: act.title,
    category: CATEGORIES[act.id] || 'Atividade',
    encounterId: act.encounterId as 1 | 2 | 3 | 4,
    encounterTitle: act.youAreHere.encounterTitle.toUpperCase(),
    recommendedTool: 'ChatGPT / Claude / Gemini',
    shortDescription: act.whyItMatters,
    templateText: fullTemplate,
    globalVarsUsed: GLOBAL_VARS_MAP[act.id] || [],
    artifactsUsed: ARTIFACTS_MAP[act.id] || [],
  };
});
